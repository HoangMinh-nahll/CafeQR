-- Cafe QR Ordering Website - PostgreSQL / Neon
-- Chạy file này một lần trên database mới.
CREATE TABLE IF NOT EXISTS users (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(100) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    full_name VARCHAR(150) NOT NULL,
    role VARCHAR(20) NOT NULL CHECK (role IN ('MANAGER', 'STAFF')),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS cafe_tables (
    table_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    table_number INTEGER NOT NULL UNIQUE CHECK (table_number BETWEEN 1 AND 10),
    table_code VARCHAR(10) NOT NULL UNIQUE,
    qr_token UUID NOT NULL UNIQUE DEFAULT gen_random_uuid(),
    is_active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS menu_categories (
    category_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_name VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS menu_items (
    item_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id BIGINT NOT NULL REFERENCES menu_categories(category_id),
    item_name VARCHAR(150) NOT NULL,
    description TEXT,
    image_url TEXT,
    is_available BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (category_id, item_name)
);

CREATE TABLE IF NOT EXISTS menu_item_variants (
    variant_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id BIGINT NOT NULL REFERENCES menu_items(item_id) ON DELETE CASCADE,
    variant_name VARCHAR(30) NOT NULL,
    price NUMERIC(12,2) NOT NULL CHECK (price >= 0),
    is_available BOOLEAN NOT NULL DEFAULT TRUE,
    UNIQUE (item_id, variant_name)
);

CREATE TABLE IF NOT EXISTS toppings (
    topping_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    topping_name VARCHAR(100) NOT NULL UNIQUE,
    additional_price NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (additional_price >= 0),
    is_available BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE IF NOT EXISTS menu_item_toppings (
    item_id BIGINT NOT NULL REFERENCES menu_items(item_id) ON DELETE CASCADE,
    topping_id BIGINT NOT NULL REFERENCES toppings(topping_id) ON DELETE CASCADE,
    PRIMARY KEY (item_id, topping_id)
);

CREATE TABLE IF NOT EXISTS customer_orders (
    order_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_code VARCHAR(60) NOT NULL UNIQUE,
    table_id BIGINT NOT NULL REFERENCES cafe_tables(table_id),
    staff_id BIGINT REFERENCES users(user_id),
    customer_note VARCHAR(500),
    status VARCHAR(20) NOT NULL DEFAULT 'NEW'
        CHECK (status IN ('NEW', 'CONFIRMED', 'PREPARING', 'READY', 'COMPLETED', 'CANCELLED')),
    total_amount NUMERIC(12,2) NOT NULL CHECK (total_amount >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS order_items (
    order_item_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES customer_orders(order_id) ON DELETE CASCADE,
    item_id BIGINT NOT NULL REFERENCES menu_items(item_id),
    variant_id BIGINT NOT NULL REFERENCES menu_item_variants(variant_id),
    item_name_snapshot VARCHAR(150) NOT NULL,
    variant_name_snapshot VARCHAR(30) NOT NULL,
    base_unit_price NUMERIC(12,2) NOT NULL CHECK (base_unit_price >= 0),
    topping_unit_total NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (topping_unit_total >= 0),
    quantity INTEGER NOT NULL CHECK (quantity BETWEEN 1 AND 20),
    line_total NUMERIC(12,2) NOT NULL CHECK (line_total >= 0)
);

CREATE TABLE IF NOT EXISTS order_item_toppings (
    order_item_id BIGINT NOT NULL REFERENCES order_items(order_item_id) ON DELETE CASCADE,
    topping_id BIGINT NOT NULL REFERENCES toppings(topping_id),
    topping_name_snapshot VARCHAR(100) NOT NULL,
    additional_price NUMERIC(12,2) NOT NULL CHECK (additional_price >= 0),
    PRIMARY KEY (order_item_id, topping_id)
);

CREATE INDEX IF NOT EXISTS idx_orders_table_created ON customer_orders(table_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_orders_status_created ON customer_orders(status, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_order_items_order ON order_items(order_id);
